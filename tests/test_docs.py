"""The rule table in docs/rules.md is generated. Run ``UPDATE_DOCS=1 python -m pytest tests/test_docs.py`` after a rule changes."""

from __future__ import annotations

import os
import re
from pathlib import Path

from routeros_lsp.rules import RULES

ROOT = Path(__file__).resolve().parent.parent


def render_rules() -> str:
    rows = []
    for rule_id in sorted(RULES):
        rule = RULES[rule_id]
        rows.append(f"| `{rule_id}` | {rule.severity} | {rule.source} | {rule.summary} | {', '.join(rule.ambiguity)} |")
    return "\n".join(
        [
            "# Diagnostic rules",
            "",
            "Generated from `src/routeros_lsp/rules.py`. Run `UPDATE_DOCS=1 python -m pytest tests/test_docs.py` after changing a rule;",
            "do not edit this file by hand.",
            "",
            "Every diagnostic has a rule id (shown as its code), a default severity and a source that says how well founded it is:",
            "",
            "| Source | Meaning |",
            "|---|---|",
            "| `doc` | The Scripting documentation states it. |",
            "| `doc-example` | The documentation does not state it but one of its examples shows it. |",
            "| `device` | Observed on RouterOS, not described in the documentation. The message says so. |",
            "| `open` | The documentation is silent or contradicts itself. The message says so. |",
            "",
            "Severities can be changed per rule with the `severities` setting; `off` disables a rule. See [configuration.md](configuration.md).",
            "The last column gives the rows of [ambiguities.md](ambiguities.md) the rule rests on.",
            "",
            "| Rule | Default | Source | Reports | Register |",
            "|---|---|---|---|---|",
            *rows,
            "",
        ]
    )


def test_lists_every_rule_in_docs_rules_md() -> None:
    path = ROOT / "docs" / "rules.md"
    expected = render_rules()
    if os.environ.get("UPDATE_DOCS"):
        path.write_text(expected, encoding="utf-8", newline="\n")
    assert path.read_text(encoding="utf-8").replace("\r\n", "\n") == expected


def test_only_names_register_rows_that_exist() -> None:
    register = (ROOT / "docs" / "ambiguities.md").read_text(encoding="utf-8")
    known = set(re.findall(r"^\| ([A-Z]-\d+) ", register, flags=re.MULTILINE))
    for rule_id, rule in RULES.items():
        for row in rule.ambiguity:
            assert row in known, f"{rule_id} cites {row}, which is not in docs/ambiguities.md"
