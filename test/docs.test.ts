import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { RULES, type RuleId } from '../src/rules.js';

const root = join(import.meta.dirname, '..');

function renderRules(): string {
  const ids = (Object.keys(RULES) as RuleId[]).sort();
  const rows = ids.map((id) => {
    const rule = RULES[id];
    const register = 'ambiguity' in rule ? rule.ambiguity.join(', ') : '';
    return `| \`${id}\` | ${rule.severity} | ${rule.source} | ${rule.summary} | ${register} |`;
  });
  return [
    '# Diagnostic rules',
    '',
    'Generated from `src/rules.ts`. Run `UPDATE_DOCS=1 npm test` after changing a rule; do not edit this file by hand.',
    '',
    'Every diagnostic has a rule id (shown as its code), a default severity and a source that says how well founded it is:',
    '',
    '| Source | Meaning |',
    '|---|---|',
    '| `doc` | The Scripting documentation states it. |',
    '| `doc-example` | The documentation does not state it but one of its examples shows it. |',
    '| `device` | Observed on RouterOS, not described in the documentation. The message says so. |',
    '| `open` | The documentation is silent or contradicts itself. The message says so. |',
    '',
    'Severities can be changed per rule with the `severities` setting; `off` disables a rule. See [configuration.md](configuration.md).',
    'The last column gives the rows of [ambiguities.md](ambiguities.md) the rule rests on.',
    '',
    '| Rule | Default | Source | Reports | Register |',
    '|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}

describe('documentation', () => {
  it('lists every rule in docs/rules.md', () => {
    const path = join(root, 'docs', 'rules.md');
    const expected = renderRules();
    if (process.env['UPDATE_DOCS']) writeFileSync(path, expected, 'utf8');
    expect(readFileSync(path, 'utf8').replace(/\r\n/g, '\n')).toBe(expected);
  });

  it('only names register rows that exist', () => {
    const register = readFileSync(join(root, 'docs', 'ambiguities.md'), 'utf8');
    const known = new Set([...register.matchAll(/^\| ([A-Z]-\d+) /gm)].map((m) => m[1]));
    for (const [id, rule] of Object.entries(RULES)) {
      for (const row of 'ambiguity' in rule ? rule.ambiguity : []) expect(known.has(row), `${id} cites ${row}, which is not in docs/ambiguities.md`).toBe(true);
    }
  });
});
